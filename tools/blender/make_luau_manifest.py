"""manifest.json (from validate.py) -> import_manifest.luau, the ModuleScript the leader fills with asset ids after the
owner uploads the models. Expected sizes / triangle counts are copied from the validated GLBs, so the Studio check
(validate_import.luau) compares against real numbers.
  python make_luau_manifest.py [manifest.json] [out.luau]"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'build', 'vis_assets', 'manifest.json')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, 'import_manifest.luau')
man = json.load(open(src))


def v3(v):
    return f'Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})'


L = ['--!strict',
     '-- MIDNIGHT PATTAYA vis assets: name -> Roblox asset ids (GENERATED by tools/blender/make_luau_manifest.py from',
     '-- build/vis_assets/manifest.json; regenerate after a pipeline run, then fill the ids again).',
     '-- modelId: the Model asset id the 3D Importer created (Asset Manager / Toolbox -> Copy Asset ID). 0 = not uploaded.',
     '-- Expected values are from validate.py (studs, Roblox axes: X right, Y up, front -Z). partSize = MeshPart.MeshSize.',
     '-- anchor: base = bbox base centre; pole = pole foot at the pivot; mount = kit module, pivot on the mount plane',
     '-- (module lies at local z <= 0); corner = pivot on the building box corner (interior at x < 0, z > 0).',
     '',
     'export type Part = {size: Vector3, tris: number, material: string}',
     'export type Asset = {modelId: number, family: string, group: string, anchor: string, collision: string,',
     '\tcanCollide: boolean, size: Vector3, tris: number, parts: {[string]: Part}}',
     '',
     'local M: {[string]: Asset} = {}',
     '']
for a in man['assets']:
    parts = ', '.join(
        f'{p["name"][len(a["name"]) + 1:]} = {{size = {v3(p["size"])}, tris = {p["tris"]}, material = "{p["material"]}"}}'
        for p in a['parts'])
    L.append(f'M.{a["name"]} = {{modelId = 0, family = "{a.get("family")}", group = "{a.get("group")}", '
             f'anchor = "{a.get("anchor")}", collision = "{a.get("collision")}", '
             f'canCollide = {str(a.get("can_collide", False)).lower()},')
    L.append(f'\tsize = {v3(a["size_studs"])}, tris = {a["tris"]}, parts = {{{parts}}}}}')
L += ['', 'return M', '']
open(dst, 'w', newline='\n').write('\n'.join(L))
print(f'{dst}: {len(man["assets"])} assets')
