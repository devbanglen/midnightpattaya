"""Turn the image asset ids from the upload into the ModuleScript ReplicatedStorage.MaterialLibraryMaps.

Input: a JSON object {"MP_<Set>_<map>": "<asset id>", ...} (the `name` column of build/materials/upload_list.json;
ids as numbers, "123", or "rbxassetid://123"). Output: build/materials/MaterialLibraryMaps.luau, e.g.
    return {
        PlasterFacadeA = {color = "rbxassetid://1", normal = "rbxassetid://2", roughness = "rbxassetid://3"},
        ...
    }
MaterialLibrary.luau reads it (ML.mapsFor / ML.studioCreateVariants). A set with no colour id is left out (the library
then keeps today's look for it); missing maps of a set are reported.

Usage (repo root):  python tools/materials/make_maps_module.py build/materials/upload_ids.json
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_pbr import OUT  # noqa: E402


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    ids = json.load(open(sys.argv[1]))
    uploads = json.load(open(os.path.join(OUT, 'upload_list.json')))
    sets, missing = {}, []
    for row in uploads:
        raw = ids.get(row['name'])
        m = re.search(r'(\d+)', str(raw)) if raw is not None else None
        if not m:
            missing.append(row['name'])
            continue
        sets.setdefault(row['set'], {})[row['map']] = f'rbxassetid://{m.group(1)}'
    lines = ['-- generated by tools/materials/make_maps_module.py from the uploaded image ids; install as',
             '-- ReplicatedStorage.MaterialLibraryMaps (ModuleScript). Set name -> map kind -> image asset id.',
             'return {']
    skipped = []
    for name in sorted(sets):
        maps = sets[name]
        if 'color' not in maps:
            skipped.append(name)
            continue
        body = ', '.join(f'{k} = "{maps[k]}"' for k in ('color', 'normal', 'roughness', 'metalness') if k in maps)
        lines.append(f'\t{name} = {{{body}}},')
    lines.append('}')
    dst = os.path.join(OUT, 'MaterialLibraryMaps.luau')
    with open(dst, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {dst}: {len(sets) - len(skipped)} sets')
    if missing:
        print('no id for: ' + ', '.join(missing))
    if skipped:
        print('left out (no colour id): ' + ', '.join(skipped))
    return 0


if __name__ == '__main__':
    sys.exit(main())
