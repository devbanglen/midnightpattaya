"""Circuit racing (Bira + the test oval): the circuit data modules, what CircuitRegistry.compile makes of them, and
a judged drive through the real CheckpointValidator + LapTimingService (luau CLI, see _circuit_harness.py).
Docs: docs/CIRCUIT_RACE_SYSTEM.md "Data interface", docs/BIRA_CIRCUIT_DESIGN.md."""
import math
import os
import re
import statistics
import unittest

import _qa
import _circuit_harness as H

DATA = os.path.join(_qa.ROOT, 'roblox', 'data', 'circuits')
REGISTRY_GATE_SPACING = (60, 120)  # CircuitRegistry header: "hidden timing gates every ~90 studs (60-120)"


def bira():
    return _qa.luau_table(os.path.join(DATA, 'bira.luau'))


def triples(flat):
    return [(flat[i], flat[i + 2], flat[i + 1]) for i in range(0, len(flat) - 2, 3)]  # (x, z, y)


class BiraData(unittest.TestCase):
    """roblox/data/circuits/bira.luau (generated by tools/circuit/bira_circuit.py), checked in Python."""

    @classmethod
    def setUpClass(cls):
        cls.d = bira()
        cls.pts = triples(cls.d['centerline'])

    def test_centerline_closed_and_evenly_spaced(self):
        pts = self.pts
        self.assertGreaterEqual(len(pts), 8)
        seg = [_qa.dist2(pts[i], pts[i + 1]) for i in range(len(pts) - 1)]
        med = statistics.median(seg)
        self.assertTrue(2 <= med <= 8, f'median spacing {med:.2f} (doc: ~4-6 studs)')
        self.assertGreater(min(seg), 0.5, 'duplicate consecutive centerline points')
        self.assertLess(max(seg), 4 * med, f'gap {max(seg):.1f} studs in the centerline')
        close = _qa.dist2(pts[-1], pts[0])
        self.assertLess(close, 4 * med, f'loop not closed: last->first {close:.1f} studs')

    def test_length_matches_lengthStuds(self):
        L = _qa.polyline_length(self.pts, closed=True)
        self.assertAlmostEqual(L, self.d['lengthStuds'], delta=0.01 * L)
        # real Bira: 2.41 km; studsPerMetre in the module
        metres = L / self.d['studsPerMetre']
        self.assertTrue(2300 <= metres <= 2550, f'{metres:.0f} m (Bira is ~2.4 km)')

    def test_width_per_point_and_sane(self):
        w = self.d['width']
        self.assertEqual(len(w), len(self.pts), 'width must be one value per centerline point')
        self.assertTrue(all(25 <= x <= 80 for x in w), f'width range {min(w)}..{max(w)}')

    def test_indices_in_range(self):
        n = len(self.pts)
        d = self.d
        for k in ('pitEntryIndex', 'pitExitIndex'):
            self.assertTrue(1 <= d[k] <= n, k)
        self.assertTrue(1 <= d['startFinish']['index'] <= n)
        s1, s2 = d['sectors']
        self.assertTrue(1 < s1 < s2 <= n, 'sectors must be increasing centerline indices')

    def test_pit_lane_joins_the_track(self):
        pit = triples(self.d['pitLane'])
        self.assertGreaterEqual(len(pit), 2)
        track = [p[:2] for p in self.pts]
        for end in (pit[0], pit[-1]):
            d = _qa.dist_to_polyline(end[:2], track, closed=True)
            self.assertLess(d, 40, f'pit lane end {end[:2]} is {d:.0f} studs from the centerline')

    def test_grid_has_enough_slots(self):
        self.assertGreaterEqual(len(self.d['grid']), 12, 'docs: grid >= 12 slots')

    def test_circuitbuilder_keys_present(self):
        """Every def.<key> CircuitBuilder reads exists in the Bira data (the builder builds the real venue)."""
        keys = set(re.findall(r'\bdef\.([A-Za-z_]\w*)', _qa.src('ServerStorage/CircuitBuilder.luau')))
        missing = sorted(k for k in keys if k not in self.d)
        self.assertEqual(missing, [])

    def test_registry_keys_present(self):
        """Every def.<key> CircuitRegistry reads exists in the data. Fixed 2026-10-20: the registry reads
        def.pitWidth or def.pitLaneWidth (Bira names it pitLaneWidth, 32.14), so pitWidth is optional."""
        reg = _qa.strip_comments(_qa.src('ServerStorage/CircuitRegistry.luau'))
        keys = set(re.findall(r'\bdef\.([A-Za-z_]\w*)', reg))
        optional = {'width', 'trackWidth', 'pitWidth'}  # width/trackWidth: one of the two (docs); pitWidth|pitLaneWidth
        missing = sorted(k for k in keys - optional if k not in self.d)
        self.assertEqual(missing, [])

    def test_grid_slot_format_matches_registry(self):
        """Grid slots are keyed {x=, y=, z=, dx=, dz=} (bira.luau) or positional {x,y,z,dx,dz}; the registry reads
        both since 2026-10-20 (before, keyed slots compiled to the world origin)."""
        reg = _qa.strip_comments(_qa.src('ServerStorage/CircuitRegistry.luau'))
        self.assertIn('s.x or s[1]', reg)
        bad = [s for s in self.d['grid'] if not (isinstance(s, list) and len(s) >= 5)
               and not (isinstance(s, dict) and {'x', 'y', 'z'} <= set(s))]
        self.assertEqual(len(bad), 0, f'{len(bad)} of {len(self.d["grid"])} grid slots have neither format')


class CompiledCircuits(unittest.TestCase):
    """The real CircuitRegistry.compile output for every roblox/data/circuits/*.luau (luau CLI)."""

    @classmethod
    def setUpClass(cls):
        cls.r = H.run()

    def setUp(self):
        self.assertEqual(self.r['code'], 0, self.r['raw'][-2000:])

    def test_all_circuits_compile(self):
        ids = H.circuit_ids()
        self.assertIn('bira', ids)
        self.assertEqual(self.r['ERR'], {})
        self.assertEqual(sorted(self.r['C']), ids)
        self.assertEqual(self.r['WARN'], [])

    def test_lap_length(self):
        for cid, c in self.r['C'].items():
            with self.subTest(cid):
                self.assertAlmostEqual(c['len'], c['lengthStuds'], delta=1.5)
                self.assertGreater(c['len'], 1000)

    def test_gates(self):
        for cid, c in self.r['C'].items():
            gates = self.r['G'][cid]
            with self.subTest(cid):
                self.assertEqual(len(gates), c['gates'])
                self.assertEqual([g['i'] for g in gates], list(range(1, len(gates) + 1)), 'gate ids 1..n, unique')
                self.assertEqual(gates[0]['s'], 0.0)
                self.assertEqual(gates[0]['line'], 1, 'gate 1 = start/finish')
                lines = sorted(g['line'] for g in gates if g['line'])
                self.assertEqual(lines, [1, 2, 3], 'one start/finish + two sector lines')
                ss = [g['s'] for g in gates] + [c['len']]
                gaps = [b - a for a, b in zip(ss, ss[1:])]
                self.assertTrue(all(b > a for a, b in zip(ss, ss[1:])), 'gates in driving order')
                lo, hi = REGISTRY_GATE_SPACING
                self.assertTrue(lo <= min(gaps) and max(gaps) <= hi, f'gate spacing {min(gaps):.0f}..{max(gaps):.0f}')
                # sectors: each at least 15% of the lap
                s1, s2 = c['s1'], c['s2']
                self.assertTrue(0.15 * c['len'] < s1 < s2 < 0.85 * c['len'])
                for g in gates:
                    self.assertTrue(10 <= g['half'] <= 40, f'gate {g["i"]} half width {g["half"]}')

    def test_bira_gate_count_expected_by_server(self):
        """Bira: lap 8,521 studs / 90 -> 96 gates, the count the circuit HUD/minimap and the judge use."""
        c = self.r['C']['bira']
        self.assertEqual(c['gates'], 96)
        self.assertEqual(c['n'], 1702)

    def test_pit_lane_compiled(self):
        for cid, p in self.r['PIT'].items():
            with self.subTest(cid):
                self.assertGreater(p['len'], 200)
                self.assertTrue(0 < p['entryS'] < p['exitS'] < p['len'], 'pit entry gate before exit gate')
                self.assertEqual(p['limit'], 60)
                bypass = [g for g in self.r['G'][cid] if g['bypass']]
                self.assertGreater(len(bypass), 0, 'pit lane must bypass some track gates')

    def test_bira_pit_width_from_data(self):
        """Compiled pit width equals the data's pitLaneWidth (was 20 before the 2026-10-20 fix)."""
        self.assertAlmostEqual(self.r['PIT']['bira']['width'], bira()['pitLaneWidth'], delta=0.01)

    def _grid_on_track(self, cid):
        grid = self.r['GRID'][cid]
        d = bira() if cid == 'bira' else None
        self.assertGreaterEqual(len(grid), 12)
        # centreline from the compiled gates' s is not printed; use the data file for bira, the oval's own numbers
        if cid == 'bira':
            pts = [p[:2] for p in triples(d['centerline'])]
            half = max(d['width']) / 2
        else:
            # test oval: main straight at z = 60000 - 111, track width 40
            pts = [(x, 60000 - 111) for x in range(59800, 60200, 5)]
            half = 20
        for i, (x, y, z, lx, lz) in enumerate(grid, 1):
            dd = _qa.dist_to_polyline((x, z), pts, closed=(cid == 'bira'))
            self.assertLess(dd, half + 5, f'{cid} grid slot {i} at ({x:.0f},{y:.0f},{z:.0f}) is {dd:.0f} studs off '
                                          f'the track')

    def test_test_oval_grid_on_track(self):
        self._grid_on_track('test_oval')

    def test_bira_grid_on_track(self):
        """The 16 Bira grid slots compile onto the track (they compiled to the world origin before 2026-10-20)."""
        self._grid_on_track('bira')

    def test_entrance_near_track(self):
        for cid, (x, y, z) in self.r['ENT'].items():
            with self.subTest(cid):
                self.assertGreater(math.hypot(x, z), 1000, 'entrance at the origin')


class JudgedDrives(unittest.TestCase):
    """Positions along the compiled centreline / pit lane fed to the real CheckpointValidator + LapTimingService."""

    @classmethod
    def setUpClass(cls):
        cls.r = H.run()

    def _laps(self, run):
        return [x for x in run['laps'].split(';') if x]

    def test_clean_two_laps(self):
        for cid, runs in self.r['RUN'].items():
            run = runs['clean2']
            with self.subTest(cid):
                self.assertEqual(run['missed'], '0')
                kinds = dict(k.split(':') for k in run['events'].split(','))
                self.assertEqual(set(kinds), {'gate'}, f'unexpected events {run["events"]}')
                self.assertEqual(int(kinds['gate']), 2 * self.r['C'][cid]['gates'] + 1)
                laps = self._laps(run)
                self.assertEqual(len(laps), 2)
                for lt in laps:
                    self.assertNotIn('!', lt, 'lap invalid')
                    self.assertAlmostEqual(float(lt), self.r['C'][cid]['len'] / 100, delta=0.5)

    def test_fast_lap_not_teleport(self):
        for cid, runs in self.r['RUN'].items():
            run = runs['fast1']
            with self.subTest(cid):
                self.assertNotIn('teleport', run['events'])
                self.assertEqual(run['missed'], '0')
                self.assertEqual(len(self._laps(run)), 1)

    def test_pit_lap(self):
        for cid, runs in self.r['RUN'].items():
            if 'pitlap' not in runs:
                continue
            run = runs['pitlap']
            with self.subTest(cid):
                kinds = dict(k.split(':') for k in run['events'].split(','))
                self.assertEqual(kinds.get('pit'), '2', 'pit on + pit off')
                self.assertNotIn('pitSpeed', kinds)
                self.assertNotIn('teleport', kinds)
                self.assertEqual(run['missed'], '0')
                laps = self._laps(run)
                self.assertGreaterEqual(len(laps), 2)
                self.assertTrue(all('!' not in x for x in laps), f'pit lap judged invalid: {laps}')


class BiraCorridorBuild(unittest.TestCase):
    """build/bira: the access corridor graph links the city start to the Bira GPS destination."""

    def test_corridor_connects_city_to_bira(self):
        g = _qa.load_json(_qa.need_build('bira', 'corridor_graph_game.json'))
        gps = _qa.src('ServerScriptService/PattayaGPSServer.server.luau')
        bira_osm = int(re.search(r'id = "bira".*?osm = (\d+)', gps).group(1))
        city = g['join_nodes']['city']
        nodes = g['nodes']
        self.assertIn(str(city), nodes)
        adj = {}
        for e in g['edges']:
            self.assertIn(str(e['a']), nodes, e['id'])
            self.assertIn(str(e['b']), nodes, e['id'])
            adj.setdefault(e['a'], set()).add(e['b'])
            adj.setdefault(e['b'], set()).add(e['a'])
        seen, todo = {city}, [city]
        while todo:
            for m in adj.get(todo.pop(), ()):
                if m not in seen:
                    seen.add(m)
                    todo.append(m)
        targets = set(g['join_nodes'].values()) - {city}
        self.assertTrue(targets, 'join_nodes has no Bira end')
        self.assertTrue(targets <= seen, 'corridor graph does not connect the city to the Bira end')
        central = _qa.load_json(_qa.need_build('central_pattaya', 'graph_game.json'))
        self.assertIn(str(city), central['nodes'], 'corridor city join node missing from the central graph')
        self.assertTrue(str(bira_osm) in nodes or bira_osm in targets,
                        f'GPS destination {bira_osm} not in the corridor graph')


