"""Writes data/osm/queries/bira_corridor_buildings.overpassql: the Overpass query for the corridor's roadside dressing.

  .venv\\Scripts\\python tools\\circuit\\corridor_dress_query.py tools\\circuit\\config\\bira.json

The search area is a polygon: every corridor road way (the `way` ids of build/bira/corridor_graph_game.json, geometry
from the corridor raw download) buffered by `corridor_dress.query_buffer_m` (220 m) in UTM, simplified by 15 m and
written as an Overpass `poly:` filter. (`way(around.<set of ways>:r)` returned nothing on overpass-api.de on
2026-10-19 while another instance returned 153 buildings for the same query, so the area is passed explicitly.)
Fetch it the way every other raw file was fetched (docs/GIS_PIPELINE.md):
  curl.exe --data-urlencode data@data/osm/queries/bira_corridor_buildings.overpassql https://overpass-api.de/api/interpreter
"""
import json, os, sys
from pyproj import Transformer
from shapely.geometry import LineString
from shapely.ops import unary_union

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def main(cfg_path):
    cfg = json.load(open(cfg_path, encoding='utf-8'))
    dc = cfg['corridor_dress']
    g = json.load(open(os.path.join(ROOT, 'build', 'bira', 'corridor_graph_game.json'), encoding='utf-8'))
    ways = sorted(set(e['way'] for e in g['edges']))
    raw = json.load(open(os.path.join(ROOT, cfg['corridor_raw']), encoding='utf-8'))
    geo = {e['id']: e['geometry'] for e in raw['elements'] if e['type'] == 'way' and e['id'] in ways}
    assert len(geo) == len(ways), 'corridor way missing from the raw download'
    fwd = Transformer.from_crs('EPSG:4326', cfg['crs'], always_xy=True)
    inv = Transformer.from_crs(cfg['crs'], 'EPSG:4326', always_xy=True)
    lines = [LineString([fwd.transform(p['lon'], p['lat']) for p in geo[w]]) for w in ways]
    area = unary_union([l.buffer(dc['query_buffer_m']) for l in lines]).simplify(15)
    assert area.geom_type == 'Polygon', area.geom_type
    ring = []
    for x, y in area.exterior.coords[:-1]:
        lon, lat = inv.transform(x, y)
        ring.append(f'{lat:.6f} {lon:.6f}')
    poly = ' '.join(ring)
    q = f'''// Roadside dressing for the Pattaya -> Bira corridor (OpenStreetMap, ODbL: "(c) OpenStreetMap contributors").
// Generated by tools/circuit/corridor_dress_query.py: the area is the {len(ways)} corridor road ways buffered by
// {dc['query_buffer_m']} m ({len(ring)}-vertex polygon); export_corridor.py keeps buildings within {dc['building_band_m']} m of the
// built corridor roads. Building footprints, landuse / natural / leisure areas, single trees and tree rows, power
// poles / towers / lines. Fetched with
//   curl.exe --data-urlencode data@data/osm/queries/bira_corridor_buildings.overpassql https://overpass-api.de/api/interpreter
[out:json][timeout:240];
(
  way["building"](poly:"{poly}");
  way["landuse"](poly:"{poly}");
  way["natural"~"^(wood|scrub|grassland|heath|wetland|water|tree_row)$"](poly:"{poly}");
  way["leisure"~"^(park|golf_course|pitch|garden)$"](poly:"{poly}");
  node["natural"="tree"](poly:"{poly}");
  node["power"~"^(pole|tower)$"](poly:"{poly}");
  way["power"~"^(line|minor_line)$"](poly:"{poly}");
);
out body geom;
'''
    dst = os.path.join(ROOT, 'data', 'osm', 'queries', 'bira_corridor_buildings.overpassql')
    open(dst, 'w', encoding='utf-8', newline='\n').write(q)
    print(f'{len(ways)} ways, polygon {len(ring)} vertices, {area.area / 1e6:.2f} km2 -> {os.path.relpath(dst, ROOT)}')


if __name__ == '__main__':
    main(sys.argv[1])
